export const LANGUAGES = ['zh', 'ja', 'en']
export const LANGUAGE_LABELS = { zh: '中文', ja: '日本語', en: 'EN' }
export const DEFAULT_LANG = 'zh'

const dicts = { zh, ja, en }

// t(key, lang, vars) — looks up key, interpolates {var} placeholders, falls back to English
export function t(key, lang, vars) {
  const str = dicts[lang]?.[key] ?? dicts.en[key] ?? key
  if (!vars) return str
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.replaceAll(`{${k}}`, v),
    str
  )
}
